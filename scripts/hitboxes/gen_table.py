"""Write src/cs2rl/env/c/cs2_hitbox_table.h, the capsule table of the sim's hitbox model (#391).

Usage, from the repository root:
    python -m scripts.hitboxes.gen_table --glb <dir>/AnimationLibrary_Godot_Standard.glb \
        --out src/cs2rl/env/c/cs2_hitbox_table.h [--check]
--check writes nothing: it exits 1 when the file at --out differs from what would be written.

WHAT the header holds (agent-local frame: fwd, left, up in sim units, feet at the origin; the
C side rotates a world ray by -facing into it, fwd = (cos facing, sin facing)):
  HB_CAPS[pose][region] = {ax, ay, az, bx, by, bz, r}, the capsule's two segment ends and radius;
  HB_GROUP[region], the CS HitGroup_t id the region reports; HB_REGION_NAMES[region];
  HB_BOUND_R/Z0/Z1[pose], a vertical cylinder that contains every capsule of the pose (an
  early-out: a ray that misses it misses every capsule); HB_REGION_HEAD / HB_REGION_NECK.
WHY the bound is computed from the ROUNDED capsules and then widened by BOUND_PAD_U: the C test
  reads the printed floats, so the cylinder must contain those, not the float64 fit, and a float32
  literal can round inward.
PITFALLS
  * The output must be stable under the repo's clang-format (the pre-commit hook reformats staged
    .h files): regenerating and then committing must not change a byte. --check after a commit
    proves it.
  * Region order is fit.REGIONS' order. The C hit test breaks an exact tie by the lower index, so
    head is region 0 (asserted below).
"""
import argparse
import math
import sys
from pathlib import Path

from . import fit

# CS HitGroup_t values (CS2 schema: HITGROUP_GENERIC 0, HEAD 1, CHEST 2, STOMACH 3, LEFTARM 4,
# RIGHTARM 5, LEFTLEG 6, RIGHTLEG 7, NECK 8). GENERIC is never produced by a capsule.
HITGROUP_ID = {
    "HEAD": 1,
    "CHEST": 2,
    "STOMACH": 3,
    "LEFTARM": 4,
    "RIGHTARM": 5,
    "LEFTLEG": 6,
    "RIGHTLEG": 7,
    "NECK": 8
}
DECIMALS = 4
BOUND_PAD_U = 1e-3


def _num(v):
    """A float literal with DECIMALS places; -0 prints as 0."""
    v = round(float(v), DECIMALS)
    return f"{0.0 if v == 0 else v:.{DECIMALS}f}f"


def build(model):
    """(scale, {pose: [(name, group, A, B, r)] rounded to DECIMALS}) in agent-local sim units."""
    poses = model.poses()
    s = fit.scale_for(model, poses["stand"])
    table = fit.sim_table(model, fit.fit_regions(model), poses, s)
    rounded = {
        p: [(n, g, [round(float(x), DECIMALS) for x in A], [round(float(x), DECIMALS)
                                                            for x in B], round(float(r), DECIMALS))
            for n, g, A, B, r in caps]
        for p, caps in table.items()
    }
    names = [c[0] for c in rounded["stand"]]
    if names[0] != "head" or names[1] != "neck":
        raise ValueError(f"region order {names[:2]}: head must be region 0 and neck region 1")
    return s, rounded


def bounding_cylinder(caps):
    """(R, z0, z1): the smallest vertical cylinder about the agent's axis holding every capsule,
    widened by BOUND_PAD_U. A segment's horizontal distance from the axis is convex along it, so
    its maximum is at an end; adding r covers the rounded caps."""
    R = max(math.hypot(P[0], P[1]) + r for _, _, A, B, r in caps for P in (A, B))
    z0 = min(P[2] - r for _, _, A, B, r in caps for P in (A, B))
    z1 = max(P[2] + r for _, _, A, B, r in caps for P in (A, B))
    q = 10**DECIMALS
    return (math.ceil((R + BOUND_PAD_U) * q) / q, math.floor(
        (z0 - BOUND_PAD_U) * q) / q, math.ceil((z1 + BOUND_PAD_U) * q) / q)


def _aligned(rows):
    """[(code, comment)] -> lines with the comments aligned one space after the longest code, as
    clang-format's AlignTrailingComments does for block comments (SpacesBeforeTrailingComments
    applies to // comments only)."""
    width = max(len(c) for c, _ in rows)
    return [f"{c:<{width}} /* {m} */" for c, m in rows]


def _macros(pairs):
    """#define lines with the values aligned, as clang-format's AlignConsecutiveMacros does."""
    width = max(len(n) for n, _ in pairs)
    return [f"#define {n:<{width}} {v}" for n, v in pairs]


def render(s, table):
    """The header text, LF line endings, ending in a newline."""
    poses = list(table)
    stand = table["stand"]
    bounds = [bounding_cylinder(table[p]) for p in poses]
    out = [
        "/* GENERATED by scripts/hitboxes/gen_table.py -- DO NOT EDIT. Regenerate from the repository",
        " * root with:",
        " *   python -m scripts.hitboxes.gen_table --glb <dir>/AnimationLibrary_Godot_Standard.glb",
        " *       --out src/cs2rl/env/c/cs2_hitbox_table.h",
        " *",
        f" * Asset: {fit.ASSET_NAME},",
        f" *   file {fit.ASSET_GLB_MEMBER},",
        f" *   sha256 {fit.ASSET_GLB_SHA256},",
        " *   from the zip",
        f" *   {fit.ASSET_ZIP_URL},",
        f" *   zip sha256 {fit.ASSET_ZIP_SHA256}.",
        " *",
        f" * License: {fit.ASSET_LICENSE};",
        " *   attribution not required.",
        " *",
        f" * Poses: stand = {fit.STAND_CLIP} t={fit.STAND_T:g}; crouch = the legs and hips translation",
        f" *   of {fit.CROUCH_CLIP} t={fit.CROUCH_T:g} under the stand pose's upper body",
        " *   (scripts/hitboxes/fit.py).",
        " *",
        f" * Fit: one capsule per region on the bind pose; radius = the p{fit.RADIUS_PERCENTILE:g} distance of",
        " *   the region's dominant-joint vertices from its axis; one scale for every pose,",
        f" *   {s:.4f} u/m, so the stand mesh top is {fit.HULL_TOP_STAND:g} u (CS:GO's standing hull).",
        " *   CS2's own hitbox dimensions are not public: these are fits to the mannequin, not",
        " *   Valve data.",
        " *",
        " * Frame: agent-local (fwd, left, up) in sim units, feet at the origin, fwd = (cos facing,",
        " * sin facing). HB_CAPS rows are {ax, ay, az, bx, by, bz, r}. */",
        "#pragma once",
        "",
    ]
    out += _macros([("HB_N_POSES", str(len(poses))), ("HB_N_REGIONS", str(len(stand)))] +
                   [(f"HB_POSE_{p.upper()}", str(i)) for i, p in enumerate(poses)] +
                   [("HB_REGION_HEAD", "0"), ("HB_REGION_NECK", "1")])
    out += ["", "/* CS HitGroup_t ids, the value HB_GROUP reports per region. */"]
    out += _macros([(f"HB_HITGROUP_{g}", str(i))
                    for g, i in sorted(HITGROUP_ID.items(), key=lambda kv: kv[1])])
    out += ["", "static const float HB_CAPS[HB_N_POSES][HB_N_REGIONS][7] = {"]
    for p in poses:
        out.append(f"    /* {p} */")
        out.append("    {")
        for n, _g, A, B, r in table[p]:
            out.append(f"        /* {n} */")
            out.append("        {" + ", ".join(_num(v) for v in (*A, *B, r)) + "},")
        out.append("    },")
    out.append("};")
    out += ["", "static const int HB_GROUP[HB_N_REGIONS] = {"]
    out += ["    " + line for line in _aligned([(f"HB_HITGROUP_{g},", n) for n, g, *_ in stand])]
    out += ["};", "", "static const char* const HB_REGION_NAMES[HB_N_REGIONS] = {"]
    out += [f'    "{n}",' for n, *_ in stand]
    out += [
        "};", "",
        "/* Early-out per pose: every capsule lies within horizontal distance HB_BOUND_R of the",
        " * agent's vertical axis and within z [HB_BOUND_Z0, HB_BOUND_Z1] (padded outward). */"
    ]
    decls = [(f"{name}[HB_N_POSES]", k)
             for name, k in (("HB_BOUND_R", 0), ("HB_BOUND_Z0", 1), ("HB_BOUND_Z1", 2))]
    width = max(len(d) for d, _ in decls)                                         # clang-format aligns the consecutive `=`
    for d, k in decls:
        out.append(f"static const float {d:<{width}} = {{" + ", ".join(_num(b[k])
                                                                       for b in bounds) + "};")
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--glb", required=True, help=f"{fit.ASSET_GLB_MEMBER} from {fit.ASSET_ZIP_URL}")
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--check", action="store_true", help="compare with --out, write nothing")
    args = ap.parse_args(argv)
    text = render(*build(fit.load_model(args.glb)))
    if args.check:
        same = args.out.exists() and args.out.read_text() == text
        print(f"{args.out}: {'up to date' if same else 'DIFFERS from the generator output'}")
        return 0 if same else 1
    args.out.write_text(text, newline="\n")
    print(f"wrote {args.out} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
